const fs=require('fs');
const vm=require('vm');
const assert=require('assert');
const path=require('path');
const root=path.join(__dirname,'..');
global.window=global;
function run(file){vm.runInThisContext(fs.readFileSync(path.join(root,file),'utf8'),{filename:file})}
run('find/land-data.js');
run('find/land-bands.js');
run('find/season-cal.js');
run('find/fp-core.js');
function load(files, names){
  const code=files.map(f=>fs.readFileSync(path.join(root,f),'utf8')).join('\n');
  return new Function(code+'\nreturn {'+names.join(',')+'};')();
}
const co=load(['drawodds/lite.js','find/labels.js'],['D','FL']);
const hist=JSON.parse(fs.readFileSync(path.join(root,'find/history/colorado.json'),'utf8'));
const pack={D:co.D,FL:co.FL,history:hist};
const q={sp:'deer',sx:'M',w:'R',se:'2',res:'nonres',pts:0,priv:0};
const a=global.RWFp.profile('co', pack, {...q, unit:'60'});
const b=global.RWFp.profile('co', pack, {...q, unit:'70'});
assert.strictEqual(a.empty, false, a.reason);
assert.strictEqual(b.empty, false, b.reason);
assert.strictEqual(a.huntId, 'DM060O2R');
assert.strictEqual(b.huntId, 'DM070O2R');
assert.strictEqual(a.pointsLikely, 0);
assert.strictEqual(b.pointsLikely, 5);
assert.strictEqual(a.oddsWord, 'LIKELY');
assert.strictEqual(b.oddsWord, 'NOT THIS YEAR');
assert.strictEqual(a.harvest, 'Good');
assert.strictEqual(b.harvest, 'High');
assert.strictEqual(a.land, 'pub');
assert.strictEqual(b.land, 'mix');
assert.strictEqual(a.trend, 'Getting easier');
assert.strictEqual(b.trend, 'Holding steady');
const line=global.RWFp.verdict([a,b]);
assert.strictEqual(line, '60 is easier to draw and has more public land, but 70 has better harvest.');
const m=global.RWFp.marks([a,b]);
assert.ok(m.points.has(0)&&!m.points.has(1));
assert.ok(m.harvest.has(1)&&!m.harvest.has(0));
assert.ok(m.land.has(0)&&!m.land.has(1));
const cal=global.RWCal;
const ut={kind:'ut-general-deer',flag:'Utah general deer',ranges:[{start:'2026-10-17',end:'2026-10-25'}]};
const rifle={kind:'co-2nd-rifle',flag:'Colorado 2nd rifle',ranges:[{start:'2026-10-24',end:'2026-11-01'}]};
const lines=cal.overlapLines([ut, rifle]);
assert.strictEqual(lines.length, 1);
assert.strictEqual(lines[0], 'Utah general deer overlaps your Colorado 2nd rifle (Oct. 24 to Oct. 25, 2026).');
const attached=cal.coAttach('deer','DM060O2R');
assert.strictEqual(attached.ranges[0].start, '2026-10-24');
assert.strictEqual(attached.ranges[0].end, '2026-11-01');
assert.strictEqual(cal.coAttach('deer','DM060L1R').ranges.length, 0);
run('find/fp-load.js');
const utPack=load(['utah/data.js'],['UH']);
const urec=global.RWLoad.record('ut', utPack, 'DB1531');
const crec=global.RWLoad.record('co', {D:co.D,FL:co.FL}, 'DM060O2R');
assert.strictEqual(urec.kind, 'ut-general-deer');
assert.strictEqual(urec.ranges[0].start, '2026-10-17');
assert.strictEqual(urec.ranges[0].end, '2026-10-25');
assert.strictEqual(crec.kind, 'co-2nd-rifle');
const live=global.RWCal.overlapLines([urec, crec]);
assert.strictEqual(live[0], 'Utah general deer overlaps your Colorado 2nd rifle (Oct. 24 to Oct. 25, 2026).');
