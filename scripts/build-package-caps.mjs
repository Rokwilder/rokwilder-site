// Package cap from official tag totals.
// 1 package per 25 tags, minimum 3, maximum 30.
// A unit is included only when every published tag for that unit is a controlled-hunt
// permit total. Units that also have a general-season season in IDFG's hunt list are
// left out, because those tags are not a per-unit quota.
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {join} from 'node:path';
import vm from 'node:vm';

const root = new URL('..', import.meta.url).pathname;
const YEAR = 2026;
const ODDS = 'https://idfg.idaho.gov/ifwis/huntplanner/api/1.1/odds/';
const SPECIES = [2, 1, 3, 6, 7, 28, 8, 4, 27];

function packageCap(tags) {
  if (!Number.isInteger(tags) || tags < 1) return null;
  return Math.min(30, Math.max(3, Math.floor(tags / 25)));
}
function norm(area) {
  const s = String(area ?? '').trim().toUpperCase();
  const m = s.match(/^0*(\d+)([A-Z]?)$/);
  return m ? String(+m[1]) + m[2] : null;
}
function parentOf(area) {
  const s = String(area ?? '').trim().toUpperCase().replace(/X$/, '');
  const sub = s.match(/^0*(\d+)([A-Z]?)-\d+[A-Z]?$/);
  if (sub) return String(+sub[1]) + sub[2];
  return norm(s);
}
const gmuRes = await fetch('https://services.arcgis.com/FjJI5xHF2dUPVrgK/arcgis/rest/services/GameManagementUnits/FeatureServer/0/query?where=1%3D1&outFields=NAME&returnGeometry=false&f=json', {headers:{'user-agent':'Rokwilder package-cap research'}});
if (!gmuRes.ok) throw new Error('GMU names ' + gmuRes.status);
const gmuJson = await gmuRes.json();
const gmuNames = new Set((gmuJson.features || []).map(f => norm(f.attributes.NAME)).filter(Boolean));

const sandbox = {window: {}};
vm.createContext(sandbox);
vm.runInContext(readFileSync(join(root, 'idaho/general-data.js'), 'utf8') + '\nglobalThis.IG=IG;', sandbox);
const generalUnits = new Set();
for (const row of sandbox.IG.seasons) {
  for (const id of String(row.area).matchAll(/\b(\d+[A-Z]?)\b/g)) {
    const key = norm(id[1]);
    if (key) generalUnits.add(key);
  }
}

async function getJson(url) {
  const res = await fetch(url, {headers: {'user-agent': 'Rokwilder package-cap research'}});
  if (!res.ok) throw new Error(res.status + ' ' + url);
  return res.json();
}

const tags = new Map();
const bad = new Set();
const hunts = [];
for (const biggame of SPECIES) {
  const payload = await getJson(`${ODDS}?biggame=${biggame}&yr=${YEAR}&draw=1`);
  for (const row of payload.rows || []) {
    const key = parentOf(row.CHuntArea);
    if (!key) continue;
    const n = Number(row.PermitTotal);
    if (!Number.isInteger(n) || n < 0) { bad.add(key); continue; }
    tags.set(key, (tags.get(key) || 0) + n);
    hunts.push({area: row.CHuntArea, unit: key, permits: n, biggame});
  }
}

const caps = {};
const detail = {};
for (const [unit, total] of [...tags.entries()].sort((a, b) => a[0].localeCompare(b[0], undefined, {numeric: true}))) {
  if (!gmuNames.has(unit) || generalUnits.has(unit) || bad.has(unit)) continue;
  const cap = packageCap(total);
  if (!cap) continue;
  caps[unit] = cap;
  detail[unit] = {tags: total, cap};
}

mkdirSync(join(root, 'data/package-caps'), {recursive: true});
writeFileSync(join(root, 'data/package-caps/idaho.json'), JSON.stringify({
  retrieved: new Date().toISOString().slice(0, 10),
  rule: '1 package per 25 official tags, minimum 3, maximum 30. floor(tags / 25), then clamp. Over-the-counter units with no per-unit quota use 30 and are not in this file.',
  source: `${ODDS}?biggame={species}&yr=${YEAR}&draw=1`,
  field: 'PermitTotal on the 2026 first drawing. Second-drawing leftovers are not added. Subunit hunts such as 36A-1 are added to the parent unit.',
  omitted: 'Units named in the Idaho general-season hunt list are omitted. Those seasons do not publish a per-unit tag total. Colorado OTC elk units and Utah general-season units with no permit cap use 30 in the page script, not in this file. Wyoming and Nevada public files do not include a unit tag total, so those hunts omit the sentence.',
  units: detail
}, null, 1) + '\n');
writeFileSync(join(root, 'find/unit-caps.js'),
  '// Generated by scripts/build-package-caps.mjs. Cap counts only, not tag totals.\n' +
  'window.RW_CAPS=' + JSON.stringify({id: caps}) + ';\n');
console.log('Idaho units with a cap', Object.keys(caps).length);
